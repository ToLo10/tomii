function normalizeDatabaseState(source) {
  const state = source && typeof source === "object" ? source : {};
  const defaults = emptyDatabase();
  for (const [key, value] of Object.entries(defaults)) {
    if (!state[key] || typeof state[key] !== "object") {
      state[key] = value;
    }
  }
  return state;
}

