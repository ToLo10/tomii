function canUserAccessRoom(roomIdOrCode, username) {
  if (!username) return false;
  const rId = getCanonicalRoomId(roomIdOrCode);
  let room = db.rooms[rId];

  if (!room && isPrivateRoom(rId)) {
    room = ensurePrivateRoomDocument(rId);
  }

  if (!room) return false;
  if (room.isPrivate) return canAccessPrivateRoom(rId, username);
  return Array.isArray(room.members) && room.members.includes(username);
}

function getRoomAudience(roomId) {
  const room = db.rooms[roomId];
  if (!room) return [];
  if (room.isPrivate) return getPrivateRoomParticipants(roomId) || [];
  return Array.isArray(room.members) ? [...new Set(room.members)] : [];
}

function normalizeReceiptEntries(entries) {
  if (!Array.isArray(entries)) return [];
  const out = [];
  const seen = new Set();
  for (const entry of entries) {
    const userId = typeof entry === "string" ? entry : entry?.userId;
    if (!userId || seen.has(userId)) continue;
    seen.add(userId);
    const user = db.users[userId] || {};
    out.push({
      userId,
      username: typeof entry === "object" && entry?.username ? entry.username : userId,
      displayName: user.displayName || userId,
      time: typeof entry === "object" ? (entry.time || "") : "",
      at: typeof entry === "object" ? (entry.at || entry.readAt || entry.deliveredAt || null) : null
    });
  }
  return out;
}

function getMessageInfo(roomId, msg) {
  const audience = getRoomAudience(roomId);
  const readBy = normalizeReceiptEntries(msg.readBy);
  const deliveredTo = normalizeReceiptEntries(msg.deliveredTo);
  const readSet = new Set(readBy.map(x => x.userId));
  const deliveredSet = new Set(deliveredTo.map(x => x.userId));

  const notReadBy = audience
    .filter(id => !readSet.has(id))
    .map(id => ({
      userId: id,
      username: id,
      displayName: db.users[id]?.displayName || id
    }));

  const notDeliveredTo = audience
    .filter(id => !deliveredSet.has(id))
    .map(id => ({
      userId: id,
      username: id,
      displayName: db.users[id]?.displayName || id
    }));

  return {
    messageId: msg.msgId,
    roomId,
    sentAt: msg.createdAt || null,
    sentTime: msg.time || "",
    readBy,
    deliveredTo,
    notReadBy,
    notDeliveredTo,
    totalRecipients: Math.max(0, audience.length - 1),
    readCount: Math.max(0, readBy.filter(x => x.userId !== msg.userId).length),
    deliveredCount: Math.max(0, deliveredTo.filter(x => x.userId !== msg.userId).length)
  };
}

// Persistent server sessions. Sessions live inside the cloud state so a Render
// restart does not automatically log every user out.
const SESSION_TTL_MS = 7 * 24 * 60 * 60 * 1000;

function issueSession(username) {
  const token = crypto.randomBytes(32).toString("hex");
  if (!db.sessions) db.sessions = {};
  db.sessions[token] = { username, expiresAt: Date.now() + SESSION_TTL_MS };
  saveDB(db);
  return token;
}

function getSession(token) {
  if (!token) return null;
  if (!db.sessions) db.sessions = {};
  const session = db.sessions[token];
  if (!session) return null;
  if (session.expiresAt <= Date.now()) {
    delete db.sessions[token];
    saveDB(db);
    return null;
  }
  return session;
}

function deleteSession(token) {
  if (!token || !db.sessions?.[token]) return;
  delete db.sessions[token];
  saveDB(db);
}

function parseCookies(cookieHeader = "") {
  const out = {};
  for (const chunk of String(cookieHeader).split(";")) {
    const idx = chunk.indexOf("=");
    if (idx === -1) continue;
    const key = chunk.slice(0, idx).trim();
    const value = chunk.slice(idx + 1).trim();
    if (key) out[key] = decodeURIComponent(value);
  }
  return out;
}

function getRequestSession(req) {
  const auth = req.headers.authorization || "";
  const bearer = auth.startsWith("Bearer ") ? auth.slice(7).trim() : "";
  const cookieToken = parseCookies(req.headers.cookie || "").chat_session;
  const token = bearer || req.headers["x-chat-session"] || cookieToken;
  const session = getSession(token);
  return session ? { ...session, token } : null;
}

function setSessionCookie(res, token) {
  const maxAgeSeconds = Math.max(60, Math.floor(SESSION_TTL_MS / 1000));
  const secure = process.env.NODE_ENV === "production" ? "; Secure" : "";
  res.setHeader(
    "Set-Cookie",
    `chat_session=${encodeURIComponent(token)}; HttpOnly; SameSite=Lax; Path=/; Max-Age=${maxAgeSeconds}${secure}`
  );
}

function clearSessionCookie(res) {
  const secure = process.env.NODE_ENV === "production" ? "; Secure" : "";
  res.setHeader("Set-Cookie", `chat_session=; HttpOnly; SameSite=Lax; Path=/; Max-Age=0${secure}`);
}

