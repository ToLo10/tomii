    user.role = safeRole;
    user.staffApproved = safeRole !== "user";
    if (safeRole === "user") user.permissions = [];
    else user.permissions = normalizePermissions(user.permissions);
    user.roleUpdatedBy = actor;
    user.roleUpdatedAt = new Date().toISOString();
    saveDB(db);

    io.to(`user_${targetUser}`).emit("my-role-updated", {
      role: getPublicRole(targetUser),
      badge: getPlatformBadge(targetUser),
      permissions: getUserPermissions(targetUser)
    });

    socket.emit("admin-action-result", {
      success: true,
      action: "set-role",
      targetUser,
      role: getPublicRole(targetUser),
      badge: getPlatformBadge(targetUser)
    });
