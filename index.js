// 🔐 Password hashing.
// New passwords use bcrypt. Legacy SHA-256 hashes remain readable and are
// upgraded automatically after the next successful login.
const LEGACY_PASSWORD_SALT = "_chatify_salt_v2024";

function legacyHashPassword(password) {
  return crypto.createHash("sha256").update(password + LEGACY_PASSWORD_SALT).digest("hex");
}

function hashPassword(password) {
  return bcrypt.hashSync(password, 12);
}

function verifyPassword(password, hash) {
  if (!hash || typeof hash !== "string") return false;
  if (hash.startsWith("$2a$") || hash.startsWith("$2b$") || hash.startsWith("$2y$")) {
    try {
      return bcrypt.compareSync(password, hash);
    } catch {
      return false;
    }
  }
  return legacyHashPassword(password) === hash;
}

function upgradePasswordHashIfNeeded(user, password) {
  if (!user || !user.password || user.password.startsWith("$2")) return;
  if (verifyPassword(password, user.password)) {
    user.password = hashPassword(password);
  }
}

// ✅ Username validation.
// Ordinary users must choose at least 4 characters.
// Short/special usernames are reserved for staff accounts created by the owner.
function validateUsername(username, options = {}) {
  if (!username || typeof username !== "string") {
    return { valid: false, error: "اسم المستخدم مطلوب" };
  }

  const trimmed = username.trim();
  const len = [...trimmed].length;
  const allowSpecial = !!options.allowSpecial;
  const minLength = allowSpecial ? 1 : 4;

  if (len < minLength) {
    return {
      valid: false,
      error: allowSpecial
        ? "اسم المستخدم غير صالح"
        : "اسم المستخدم للمستخدم العادي يجب أن يكون 4 أحرف على الأقل"
    };
  }

  if (len > 32) {
    return { valid: false, error: "اسم المستخدم يجب ألا يتجاوز 32 حرفاً" };
  }

  if (/\s/.test(trimmed)) {
    return { valid: false, error: "اسم المستخدم لا يمكن أن يحتوي على مسافات" };
  }

  return { valid: true, role: "user", username: trimmed };
}

