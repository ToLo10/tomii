// 📊 Get user stats
function getUserStats(username) {
  let friendsCount = 0;
  if (db.friends) {
    for (const key in db.friends) {
      const parts = key.split("_");
      if (parts.length === 2 && (parts[0] === username || parts[1] === username)) {
        friendsCount++;
      }
    }
  }
  let requestsCount = 0;
  if (db.friendRequests) {
    for (const key in db.friendRequests) {
      if (db.friendRequests[key].toUser === username) requestsCount++;
    }
  }
  return { friendsCount, requestsCount };
}

// 🆕 Generate a cryptographically-strong room/share code
function generateShareCode(length = 10) {
  const chars = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
  const bytes = crypto.randomBytes(length);
  let code = "";
  for (let i = 0; i < length; i++) {
    code += chars[bytes[i] % chars.length];
  }
  return code;
}

function generateUniqueRoomCode() {
  let code;
  do {
    code = generateShareCode(10);
  } while (db.rooms[code] || Object.values(db.rooms).some(room => room && room.shareCode === code));
  return code;
}

