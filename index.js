app.post("/api/room/ban", requireHttpAuth, (req, res) => {
  try {
    const { roomId: roomIdOrCode, targetUser, duration, reason, isPermanent } = req.body;
    const actor = req.authUser;
    if (!roomIdOrCode || !targetUser) {
      return res.status(400).json({ error: "بيانات غير كاملة" });
    }

    const roomId = getCanonicalRoomId(roomIdOrCode);
    const staff = isRoomStaff(roomId, actor);
    if (!staff) return res.status(403).json({ error: "ليس لديك صلاحية الحظر" });
    if (targetUser === PLATFORM_OWNER_USERNAME) {
      return res.status(403).json({ error: "لا يمكن حظر مالك المنصة" });
    }

    if (!db.roomBans[roomId]) db.roomBans[roomId] = {};
    const minutes = Math.max(1, Number.parseInt(duration, 10) || 60);
    const expiresAt = isPermanent ? null : new Date(Date.now() + minutes * 60000).toISOString();

    db.roomBans[roomId][targetUser] = {
      bannedBy: actor,
      reason: String(reason || "").slice(0, 500),
      isPermanent: !!isPermanent,
      expiresAt,
      createdAt: new Date().toISOString()
    };

    if (Array.isArray(db.rooms[roomId]?.members)) {
      db.rooms[roomId].members = db.rooms[roomId].members.filter(id => id !== targetUser);
    }
    saveDB(db);

    const liveRoom = io.sockets.adapter.rooms.get(roomId);
    if (liveRoom) {
      for (const socketId of liveRoom) {
        const clientSocket = io.sockets.sockets.get(socketId);
        if (clientSocket?.userId === targetUser) {
          clientSocket.emit("banned-from-room", {
            message: isPermanent ? "تم حظرك دائماً من هذه الغرفة" : "تم حظرك مؤقتاً من هذه الغرفة",
            reason: reason || "",
            expiresAt
          });
          clientSocket.leave(roomId);
        }
      }
    }

    res.json({ success: true, message: "تم الحظر بنجاح" });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

