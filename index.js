  // =======================================================
  function validatePrivateCallTarget(roomIdOrCode, targetUser) {
    const actor = socket.userId;
    if (!actor || !roomIdOrCode) return null;

    const rId = getCanonicalRoomId(roomIdOrCode);
    const roomDoc = ensurePrivateRoomDocument(rId);
    if (!roomDoc || roomDoc.isPrivate !== true || !canAccessPrivateRoom(rId, actor)) return null;

    const members = Array.isArray(roomDoc.members) ? roomDoc.members : (getPrivateRoomParticipants(rId) || []);
    if (members.length !== 2) return null;

    const other = members.find(id => id !== actor);
    if (!other || (targetUser && targetUser !== other)) return null;
    return { rId, actor, targetUser: other, roomDoc };
  }

  function emitPrivateCallEvent(valid, eventName, payload = {}) {
    // Call signaling is delivered through the user's personal Socket.IO room.
    // Do not move the socket away from the conversation the user is currently browsing.
    io.to(`user_${valid.targetUser}`).emit(eventName, {
      roomId: valid.rId,
      fromUser: valid.actor,
      ...payload
    });
  }

