function emitRoomMembers(roomId) {
  const roomDoc = db.rooms[roomId];
  if (!roomDoc || roomDoc.isPrivate) return;

  const members = (Array.isArray(roomDoc.members) ? roomDoc.members : []).map(memberId => {
    const user = db.users[memberId] || {};
    return {
      userId: memberId,
      username: memberId,
      displayName: user.displayName || memberId,
      role: getPublicRole(memberId),
      badge: roomDoc.owner === memberId
        ? "owner"
        : (roomDoc.moderators?.includes(memberId) ? "moderator" : getPublicRole(memberId)),
      platformBadge: getPlatformBadge(memberId),
      isOnline: activeOnlineUsers.has(memberId),
      isOwner: roomDoc.owner === memberId,
      isModerator: roomDoc.moderators?.includes(memberId) || false,
      avatar: user.avatar || "",
      frame: getActiveFrame(memberId)
    };
  });

  io.to(roomId).emit("room-members-list", {
    roomId,
    owner: roomDoc.owner,
    maxUsers: normalizeMaxUsers(roomDoc.maxUsers, 24),
    members
  });
}

function broadcastRoomUsers(roomId) {
  const room = io.sockets.adapter.rooms.get(roomId);
  const users = [];
  const seen = new Set();

  const roomDoc = db.rooms[roomId];

  if (room) {
    for (const socketId of room) {
      const clientSocket = io.sockets.sockets.get(socketId);
      if (clientSocket && clientSocket.userId && !seen.has(clientSocket.userId)) {
        seen.add(clientSocket.userId);
        const user = db.users[clientSocket.userId] || {};
        let badge = null;
        if (roomDoc) {
          if (roomDoc.owner === clientSocket.userId) badge = "owner";
          else if (roomDoc.moderators && roomDoc.moderators.includes(clientSocket.userId)) badge = "moderator";
          else {
            const platformRole = getPublicRole(clientSocket.userId);
            if (platformRole !== "user") badge = platformRole;
          }
        }
        users.push({
          userId: clientSocket.userId,
          username: clientSocket.userId,
          displayName: user.displayName || clientSocket.userId,
          role: getPublicRole(clientSocket.userId),
          badge,
          platformBadge: getPlatformBadge(clientSocket.userId),
          permissions: getUserPermissions(clientSocket.userId),
          avatar: user.avatar || "",
          frame: getActiveFrame(clientSocket.userId)
        });
      }
    }
  }
  io.to(roomId).emit("room-users-list", users);
  io.to(roomId).emit("query-room-users-response", { roomId, users });

  if (roomDoc && !roomDoc.isPrivate) {
    emitRoomMembers(roomId);
  }
}

function broadcastOnlineUsers() {
  const onlineList = Array.from(activeOnlineUsers.keys());
  io.emit("online_users_list", onlineList);
}

