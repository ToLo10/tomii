function filterBrowserBlockedTurnUrls(iceServers) {
  if (!Array.isArray(iceServers)) return [];

  return iceServers.map(server => {
    if (!server || typeof server !== "object") return null;
    const rawUrls = Array.isArray(server.urls) ? server.urls : [server.urls];
    const urls = rawUrls
      .map(value => String(value || "").trim())
      .filter(Boolean)
      // Cloudflare documents port 53 as commonly blocked by browsers.
      .filter(url => !/:53(?:\?|$)/i.test(url));

    if (!urls.length) return null;
    const normalized = {
      urls: urls.length === 1 ? urls[0] : urls
    };
    if (server.username) normalized.username = String(server.username);
    if (server.credential) normalized.credential = String(server.credential);
    return normalized;
  }).filter(Boolean);
}

async function getCloudflareTurnCredentials(username) {
  if (!CLOUDFLARE_TURN_CONFIGURED) return null;

  const cacheKey = String(username || "anonymous");
  const cached = cloudflareTurnCredentialCache.get(cacheKey);
  const now = Date.now();

  // Reuse credentials until 15 minutes before expiry. This reduces calls to
  // Cloudflare while still ensuring a fresh credential before a new call.
  if (cached && cached.expiresAt - now > 15 * 60 * 1000) {
    return cached;
  }

  const endpoint = `https://rtc.live.cloudflare.com/v1/turn/keys/${encodeURIComponent(CLOUDFLARE_TURN_KEY_ID)}/credentials/generate-ice-servers`;
  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${CLOUDFLARE_TURN_API_TOKEN}`,
      "Content-Type": "application/json"
    },
    body: JSON.stringify({ ttl: CLOUDFLARE_TURN_TTL_SECONDS })
  });

  if (!response.ok) {
    let detail = "";
    try { detail = (await response.text()).slice(0, 300); } catch (_) {}
    throw new Error(`Cloudflare TURN credential request failed (${response.status})${detail ? `: ${detail}` : ""}`);
  }

  const payload = await response.json();
  const iceServers = filterBrowserBlockedTurnUrls(payload?.iceServers);
  const hasTurn = iceServers.some(server => {
    const urls = Array.isArray(server.urls) ? server.urls : [server.urls];
    return urls.some(url => /^turns?:/i.test(String(url || "")));
  });

  if (!hasTurn) {
    throw new Error("Cloudflare TURN returned no TURN relay URLs");
  }

  const result = {
    iceServers,
    expiresAt: now + CLOUDFLARE_TURN_TTL_SECONDS * 1000,
    ttl: CLOUDFLARE_TURN_TTL_SECONDS,
    provider: "cloudflare",
    turnConfigured: true
  };
  cloudflareTurnCredentialCache.set(cacheKey, result);
  return result;
}

