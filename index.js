function bindSocketUser(socket, username) {
  const user = db.users[username];
  if (!user) return false;

  socket.username = username;
  socket.userId = username;
  socket.role = getPublicRole(username);
  socket.join(`user_${username}`);

  if (!activeOnlineUsers.has(username)) {
    activeOnlineUsers.set(username, new Set());
  }
  activeOnlineUsers.get(username).add(socket.id);

  user.lastSeen = new Date().toISOString();
  user.status = "online";
  saveDB(db);
  return true;
}

io.use((socket, next) => {
  try {
    const cookieToken = parseCookies(socket.handshake.headers.cookie || "").chat_session;
    const authToken = socket.handshake.auth?.sessionToken;
    const session = getSession(authToken || cookieToken);

    if (session && db.users[session.username]) {
      const ban = checkPlatformBan(session.username);
      if (!ban.banned) {
        socket.sessionToken = authToken || cookieToken;
        socket.sessionUser = session.username;
        socket.userId = session.username;
        socket.username = session.username;
        socket.role = getPublicRole(session.username);
      }
    }
  } catch (err) {
    console.error("Socket session check failed:", err.message);
  }
  next();
});

function attachSocketToConversation(socket, roomId) {
  if (!socket || !roomId) return;

  const previousRoomId = socket.roomId;

  if (previousRoomId && previousRoomId !== roomId) {
    socket.leave(previousRoomId);
  }

  socket.join(roomId);
  socket.roomId = roomId;

  if (previousRoomId && previousRoomId !== roomId) {
    setImmediate(() => broadcastRoomUsers(previousRoomId));
  }
}

