// 🛡️ Check room ban
function checkRoomBan(roomId, userId) {
  if (!db.roomBans || !db.roomBans[roomId]) return { banned: false };
  const ban = db.roomBans[roomId][userId];
  if (!ban) return { banned: false };
  if (ban.isPermanent) {
    return { banned: true, reason: ban.reason || "", type: "permanent", bannedBy: ban.bannedBy };
  }
  if (ban.expiresAt && new Date(ban.expiresAt) > new Date()) {
    return { banned: true, reason: ban.reason || "", type: "temporary", expiresAt: ban.expiresAt, bannedBy: ban.bannedBy };
  }
  // Expired ban - remove it
  delete db.roomBans[roomId][userId];
  saveDB(db);
  return { banned: false };
}

